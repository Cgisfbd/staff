/// Ergonomic extension on BuildContext for quick localization access (< 25 lines).
extension AppLocalizationContext on BuildContext {
  String tr(String key, {Map<String, String>? params}) {
    String langCode = 'en';
    try {
      langCode = watch<LocaleCubit>().state.languageCode;
    } catch (_) {
      try {
        langCode = read<LocaleCubit>().state.languageCode;
      } catch (_) {}
    }
    return AppStrings.get(key, langCode, params: params);
  }

  bool get isRtl {
    try {
      return watch<LocaleCubit>().state.isRtl;
    } catch (_) {
      try {
        return read<LocaleCubit>().state.isRtl;
      } catch (_) {
        return false;
      }
    }
  }

  String get currentLanguageCode {
    try {
      return watch<LocaleCubit>().state.languageCode;
    } catch (_) {
      try {
        return read<LocaleCubit>().state.languageCode;
      } catch (_) {
        return 'en';
      }
    }
  }
}
