  factory StudentDirectoryModel.fromJson(Map<String, dynamic> json) {
    return StudentDirectoryModel(
      id: json['id']?.toString() ?? '',
      rollNo: (json['rollNo'] ?? json['roll_no'] ?? 0) is int
          ? (json['rollNo'] ?? json['roll_no'] ?? 0) as int
          : int.tryParse((json['rollNo'] ?? json['roll_no'] ?? '0').toString()) ?? 0,
      status: json['status']?.toString() ?? 'Active',
      fullNameEn: json['fullNameEn']?.toString() ?? json['full_name_en']?.toString() ?? '',
      nameUrdu: json['nameUrdu']?.toString() ?? json['name_urdu']?.toString() ?? json['fullNameUr']?.toString() ?? '',
