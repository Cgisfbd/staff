      fatherNameUr: json['fatherNameUr']?.toString() ?? json['father_name_ur']?.toString() ?? '',
      fatherOccupation: json['fatherOccupation']?.toString() ?? json['father_occupation']?.toString() ?? '',
      motherNameEn: json['motherNameEn']?.toString() ?? json['mother_name_en']?.toString() ?? '',
      motherNameUr: json['motherNameUr']?.toString() ?? json['mother_name_ur']?.toString() ?? '',
      motherOccupation: json['motherOccupation']?.toString() ?? json['mother_occupation']?.toString() ?? '',
      dob: json['dob']?.toString() ?? '',
      gender: json['gender']?.toString() ?? 'Male',
      caste: json['caste']?.toString() ?? '',
      aadharNo: json['aadharNo']?.toString() ?? json['aadhar_no']?.toString() ?? '',
      rfidNo: json['rfidNo']?.toString() ?? json['rfid_no']?.toString() ?? '',
      photoUrl: json['photoUrl']?.toString() ?? json['photo_url']?.toString() ?? json['avatar']?.toString(),
      mobile: json['mobile']?.toString() ?? '',
      altMobile: json['altMobile']?.toString() ?? json['alt_mobile']?.toString() ?? '',
      fullAddress: json['fullAddress']?.toString() ?? json['full_address']?.toString() ?? json['address']?.toString() ?? '',
      courseId: json['courseId']?.toString() ?? json['course_id']?.toString(),
      courseName: json['courseName']?.toString() ?? json['course_name']?.toString() ?? '',
      classId: json['classId']?.toString() ?? json['class_id']?.toString(),
      className: json['className']?.toString() ?? json['class_name']?.toString() ?? json['class']?.toString() ?? '',
      modeOfStudy: json['modeOfStudy']?.toString() ?? json['mode_of_study']?.toString() ?? 'Offline',
      hostelFacility: json['hostelFacility']?.toString() ?? json['hostel_facility']?.toString() ?? 'Yes',
      prevSchoolName: json['prevSchoolName']?.toString() ?? json['prev_school_name']?.toString() ?? '',
      prevSchoolAddress: json['prevSchoolAddress']?.toString() ?? json['prev_school_address']?.toString() ?? '',
      admissionDate: json['admissionDate']?.toString() ?? json['admission_date']?.toString() ?? '',
      submittedDocs: (json['submittedDocs'] ?? json['submitted_docs'] ?? json['documents']) is List
          ? ((json['submittedDocs'] ?? json['submitted_docs'] ?? json['documents']) as List)
              .map((e) => e.toString())
              .toList()
          : ((json['submittedDocs'] ?? json['submitted_docs'] ?? json['documents'])?.toString().split(',') ??
                  const <String>[])
              .where((s) => s.trim().isNotEmpty)
              .map((s) => s.trim())
              .toList(),
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'rollNo': rollNo,
      'status': status,
      'fullNameEn': fullNameEn,
      'nameUrdu': nameUrdu,
      'fatherNameEn': fatherNameEn,
      'fatherNameUr': fatherNameUr,
      'fatherOccupation': fatherOccupation,
      'motherNameEn': motherNameEn,
      'motherNameUr': motherNameUr,
      'motherOccupation': motherOccupation,
      'dob': dob,
      'gender': gender,
      'caste': caste,
      'aadharNo': aadharNo,
      'rfidNo': rfidNo,
      'photoUrl': photoUrl,
      'mobile': mobile,
      'altMobile': altMobile,
      'fullAddress': fullAddress,
      'courseId': courseId,
      'courseName': courseName,
      'classId': classId,
      'className': className,
      'modeOfStudy': modeOfStudy,
      'hostelFacility': hostelFacility,
      'prevSchoolName': prevSchoolName,
      'prevSchoolAddress': prevSchoolAddress,
      'admissionDate': admissionDate,
      'submittedDocs': submittedDocs,
    };
  }

