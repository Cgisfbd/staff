/// Data model representing student stats response from backend.
class StudentStatsModel extends StudentStatsEntity {
  const StudentStatsModel({
    required super.totalActive,
    required super.activeCount,
    required super.dropoutCount,
    required super.graduatedCount,
    required super.offlineCount,
    required super.onlineCount,
    required super.rfidLinked,
  });

  factory StudentStatsModel.fromJson(Map<String, dynamic> json) {
    return StudentStatsModel(
      totalActive: (json['totalActive'] ?? json['total_active'] ?? 0) as int,
      activeCount: (json['activeCount'] ?? json['active_count'] ?? json['totalActive'] ?? 0) as int,
      dropoutCount: (json['dropoutCount'] ?? json['dropout_count'] ?? 0) as int,
      graduatedCount: (json['graduatedCount'] ?? json['graduated_count'] ?? 0) as int,
      offlineCount: (json['offlineCount'] ?? json['offline_count'] ?? 0) as int,
      onlineCount: (json['onlineCount'] ?? json['online_count'] ?? 0) as int,
      rfidLinked: (json['rfidLinked'] ?? json['rfid_linked'] ?? 0) as int,
    );
  }

