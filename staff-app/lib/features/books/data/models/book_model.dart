import 'package:staff_app/features/books/domain/entities/book_entity.dart';

class BookModel extends BookEntity {
  const BookModel({
    required super.id,
    required super.simpleId,
    required super.subjectId,
    super.subjectName,
    super.className,
    super.courseName,
    required super.nameEnglish,
    required super.nameUrdu,
    super.category = 'DEENI',
    super.term = 'FULL_YEAR',
    super.maxMarks = 100,
    super.passMarks = 33,
    super.theoryMarks = 100,
    super.practicalMarks = 0,
  });

  factory BookModel.fromJson(Map<String, dynamic> json) {
    return BookModel(
      id: json['id']?.toString() ?? '',
      simpleId: (json['simpleId'] as num?)?.toInt() ?? 1,
      subjectId: json['subjectId']?.toString() ?? '',
      subjectName: json['subjectName']?.toString() ?? 'Academic Subject',
      className: json['className']?.toString(),
      courseName: json['courseName']?.toString(),
      nameEnglish: json['nameEnglish']?.toString() ?? '',
      nameUrdu: json['nameUrdu']?.toString() ?? '',
      category: json['category']?.toString() ?? 'DEENI',
      term: json['term']?.toString() ?? 'FULL_YEAR',
      maxMarks: (json['maxMarks'] as num?)?.toInt() ?? 100,
      passMarks: (json['passMarks'] as num?)?.toInt() ?? 33,
      theoryMarks: (json['theoryMarks'] as num?)?.toInt() ?? 100,
      practicalMarks: (json['practicalMarks'] as num?)?.toInt() ?? 0,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'simpleId': simpleId,
      'subjectId': subjectId,
      'subjectName': subjectName,
      if (className != null) 'className': className,
      if (courseName != null) 'courseName': courseName,
      'nameEnglish': nameEnglish,
      'nameUrdu': nameUrdu,
      'category': category,
      'term': term,
      'maxMarks': maxMarks,
      'passMarks': passMarks,
      'theoryMarks': theoryMarks,
      'practicalMarks': practicalMarks,
    };
  }

