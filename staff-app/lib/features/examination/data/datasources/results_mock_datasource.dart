  List<StudentResultModel> getClassResults(String classId) {
    return _classResults[classId] ?? _classResults['cls_aal_1']!;
  }

  List<StudentResultModel> getAllInstituteResults() {
    final seen = <String>{};
    final all = <StudentResultModel>[];
    for (final list in _classResults.values) {
      for (final s in list) {
        if (seen.add(s.studentId)) {
          all.add(s);
        }
      }
    }
    all.sort((a, b) => b.percentage.compareTo(a.percentage));
    return all;
  }

  List<StudentResultModel> getCourseResults(String courseName) {
    final seen = <String>{};
    final all = <StudentResultModel>[];
    final query = courseName.toLowerCase();
    for (final list in _classResults.values) {
      for (final s in list) {
        if (s.courseName.toLowerCase().contains(query) && seen.add(s.studentId)) {
          all.add(s);
        }
      }
    }
    if (all.isEmpty) {
      return getClassResults('cls_aal_1');
    }
    all.sort((a, b) => b.percentage.compareTo(a.percentage));
    return all;
  }
